<?php

declare(strict_types=1);

/*
 * Builds database/schema.sql: every migration in one file, for importing into an
 * EMPTY database with phpMyAdmin (an alternative to letting /install create the tables).
 * It also records the migrations as applied, so the site does not run them again.
 *
 * Usage: php tools/build-schema.php [output-file]
 * Re-run whenever a migration is added; tests check the file is up to date.
 */

$root = dirname(__DIR__);
$files = glob($root . '/database/migrations/*.sql') ?: [];
sort($files, SORT_STRING);

$out = [];
$out[] = '-- =====================================================================';
$out[] = '-- SMART Circle v2 — complete database (generated by tools/build-schema.php)';
$out[] = '-- DO NOT EDIT BY HAND: edit database/migrations/ and re-run the tool.';
$out[] = '--';
$out[] = '-- Import into an EMPTY database (phpMyAdmin > Import). Then open /install on';
$out[] = '-- the site to create your tutor account. See docs/database.md.';
$out[] = '-- =====================================================================';
$out[] = '';
$out[] = 'SET NAMES utf8mb4;';
$out[] = 'SET FOREIGN_KEY_CHECKS = 0;';
$out[] = '';

$versions = [];
foreach ($files as $file) {
    $version = basename($file, '.sql');
    $versions[] = $version;
    $out[] = '-- ---------------------------------------------------------------------';
    $out[] = "-- Migration $version";
    $out[] = '-- ---------------------------------------------------------------------';
    $out[] = rtrim((string) file_get_contents($file));
    $out[] = '';
}

$out[] = '-- Record the migrations above as applied.';
$out[] = 'CREATE TABLE IF NOT EXISTS schema_migrations (';
$out[] = '    version    VARCHAR(100) NOT NULL PRIMARY KEY,';
$out[] = '    applied_at DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP';
$out[] = ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;';
$out[] = 'INSERT INTO schema_migrations (version) VALUES ' . implode(', ', array_map(static fn (string $v): string => "('$v')", $versions)) . ';';
$out[] = '';
$out[] = 'SET FOREIGN_KEY_CHECKS = 1;';
$out[] = '';

$target = $argv[1] ?? $root . '/database/schema.sql';
file_put_contents($target, implode("\n", $out));
echo 'Wrote ' . $target . ' (' . count($versions) . ' migrations, ' . filesize($target) . " bytes)\n";

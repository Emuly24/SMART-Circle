<?php

declare(strict_types=1);

/*
 * Generates database/migrations/0005_topics.sql from database/seeds/topics.txt.
 * Usage: php tools/generate-topic-seed.php [output-file]
 * (Only regenerate before 0005 has been applied anywhere; afterwards, change topics in
 * Studio > Topics or add a new migration.)
 */

use SmartCircle\Application\Topics\TopicLineParser;
use SmartCircle\Support\Subjects;

require dirname(__DIR__) . '/config/bootstrap.php';

$root = dirname(__DIR__);
$lines = file($root . '/database/seeds/topics.txt', FILE_IGNORE_NEW_LINES) ?: [];
$q = static fn (?string $s): string => $s === null ? 'NULL' : "'" . str_replace(['\\', "'"], ['\\\\', "''"], $s) . "'";

$sql = [
    '-- SMART Circle v2 — starting topic catalogue (generated by tools/generate-topic-seed.php',
    '-- from database/seeds/topics.txt). Forms 3-4 Maths/Physics/Chemistry/Biology come from the',
    '-- tutor\'s old list; Forms 1-2 and English grammar are DRAFTS to check against the syllabus.',
    '',
];
$form = 0;
$subject = '';
$order = 0;
$counts = [];

foreach ($lines as $n => $line) {
    if (preg_match('/^##\s+([1-4])\s+([a-z]+)\s*$/', trim($line), $m)) {
        [$form, $subject, $order] = [(int) $m[1], $m[2], 0];
        if (!isset(Subjects::NAMES[$subject])) {
            fwrite(STDERR, "Line " . ($n + 1) . ": unknown subject $subject\n");
            exit(1);
        }
        continue;
    }
    $topic = TopicLineParser::parse($line);
    if ($topic === null || $form === 0) {
        continue;
    }
    $order += 10;
    $counts["$form $subject"] = ($counts["$form $subject"] ?? 0) + 1;
    $sql[] = sprintf(
        'INSERT INTO topics (form, subject, unit, title, sort_order) VALUES (%d, %s, %s, %s, %d);',
        $form, $q($subject), $q($topic['unit']), $q($topic['title']), $order
    );
    if ($topic['subtopics'] !== []) {
        $sql[] = 'SET @parent = LAST_INSERT_ID();';
        $values = [];
        foreach ($topic['subtopics'] as $i => $sub) {
            $values[] = sprintf('(%d, %s, @parent, %s, %d)', $form, $q($subject), $q($sub), ($i + 1) * 10);
        }
        $sql[] = 'INSERT INTO topics (form, subject, parent_id, title, sort_order) VALUES ' . implode(', ', $values) . ';';
    }
}

$target = $argv[1] ?? $root . '/database/migrations/0005_topics.sql';
file_put_contents($target, implode("\n", $sql) . "\n");
ksort($counts);
echo "Wrote $target\n";
foreach ($counts as $key => $c) {
    echo "  Form $key: $c topics\n";
}

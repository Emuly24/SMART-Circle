        <h1>About SMART Circle</h1>
        <p class="lead">
            SMART stands for <strong>Student Mentorship, Academic Readiness and Technology</strong>.
            It is a free programme that gives extra support to Form 1–4 students in Mathematics,
            Physics, Chemistry, Biology and English grammar.
        </p>

        <h2>Who teaches</h2>
        <p>
            SMART Circle is run by a science graduate and tutor with a passion for helping students
            who struggle in science subjects. The tutor is not a trained teacher, so lessons are
            checked against the national syllabus with the help of partner teachers.
        </p>

        <h2>How lessons are made</h2>
        <ul>
            <li>Students request help only on topics their school has already covered.</li>
            <li>Each request says exactly where the student gets stuck.</li>
            <li>The tutor records a lesson for that need, on a digital board, with real-life examples.</li>
            <li>Students watch, answer questions, and keep discussing until it makes sense.</li>
        </ul>

        <h2>Keeping students safe</h2>
        <p>
            Our students are young. All discussion happens in spaces the whole class can see,
            there are no private messages between students, and guardians give consent before
            a student joins.
        </p>
    </div>
</section>

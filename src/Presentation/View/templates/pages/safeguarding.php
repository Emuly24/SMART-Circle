        <p class="eyebrow">Safeguarding and privacy</p>
        <h1>How we keep students safe</h1>
        <p class="lead">Our students are young people. Their safety, dignity and privacy come before everything else we do.</p>

        <h2>Our promises</h2>
        <ul>
            <li><strong>Free, without favours of any kind.</strong> SMART Circle never asks for money, gifts, or sexual or any other favours, and never will. Anyone who asks for such a thing in our name is not part of SMART Circle.</li>
            <li><strong>Guardians know.</strong> A parent or guardian agrees before a student applies, and knows about the pledge the student makes.</li>
            <li><strong>Everything stays on the site.</strong> Lessons, messages and support conversations happen inside SMART Circle, where they are kept. They are never moved to private phone chats.</li>
            <li><strong>No private messages between students.</strong> Students talk in lesson discussions that the class and the tutor can see.</li>
            <li><strong>The private support room is for studies only.</strong> It is there to understand issues that affect a student’s learning. Guardians are told when the tutor invites their child to it (not what is said), and nothing in it can be deleted.</li>
            <li><strong>No private meetings.</strong> The tutor does not arrange to meet students privately outside the programme.</li>
            <li><strong>Serious concerns are referred.</strong> If a student tells us they are being harmed or are in danger, we listen, and we refer it to people who can help: the District Social Welfare Office, the Police Victim Support Unit, or the Child Helpline.</li>
        </ul>

        <h2>If you are worried</h2>
        <p>Tell someone you trust: your parent or guardian, a teacher, or the tutor. In Malawi you can also call the free <strong>Child Helpline on 116</strong>.</p>
        <p>To raise a concern about SMART Circle itself, email <strong><?= e($contactEmail ?? 'smartcircle@zohomail.com') ?></strong>.</p>

        <h2>Your information</h2>
        <p>We follow Malawi’s Data Protection Act. In short:</p>
        <ul>
            <li><strong>What we keep:</strong> the details in your application and sign-up, your school, your guardian’s contact, and your work on the site (requests, answers, marks).</li>
            <li><strong>Why:</strong> only to choose students fairly, teach you, follow your progress and contact you or your guardian about your studies.</li>
            <li><strong>Who sees it:</strong> the tutor. Partner teachers see only numbers about their school, never names. We never sell or share your information for advertising.</li>
            <li><strong>Your rights:</strong> you may ask to see what we keep about you, to correct it, or to have it deleted when you leave, unless we must keep a record (for example a signed pledge or a safety concern).</li>
            <li><strong>Security:</strong> passwords are stored scrambled, every page uses a secure connection, and school reports are visible only to the tutor.</li>
        </ul>

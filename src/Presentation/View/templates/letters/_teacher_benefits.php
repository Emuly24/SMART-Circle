<?php
/**
 * Why SMART Circle needs school teachers, what they can do and what they gain (in partner letters).
 * @var string $subjects e.g. "Mathematics, Physics"
 */
$in = $subjects !== '' ? $subjects : 'your subjects';
?>
<h2>Why we need you</h2>
<ul>
    <li><strong>Honesty with schools.</strong> We only explain again what a student's school has <em>already taught</em>. Only a teacher can tell us reliably what has been covered, so we never run ahead of you.</li>
    <li><strong>Accuracy.</strong> Every lesson and set of notes should be checked by a qualified teacher before students rely on it. Your name and signature on our materials tell students and parents they are right.</li>
    <li><strong>Your experience.</strong> You know where students struggle. The questions you suggest and the topics you flag make our support fit real classrooms.</li>
    <li><strong>Your students' own books.</strong> Chapter and page references from your textbooks let every lesson point students back to the book they use in class.</li>
</ul>
<h2>What you can do (choose what suits you)</h2>
<ul>
    <li>Tell us which topics in <strong><?= e($in) ?></strong> your school has taught: a few minutes a month, from your phone.</li>
    <li>Check our notes and recorded lessons in your subjects, and approve them with your signature or suggest changes.</li>
    <li>Suggest exercise and exam questions, confirm your school's term dates, and share a syllabus or scheme of work.</li>
    <li>If you wish, record lessons yourself as a <em>guest teacher</em>; they are published with your name.</li>
</ul>
<h2>What you gain</h2>
<ul>
    <li><strong>Free extra support for your own students.</strong> Those admitted get recorded lessons, notes and encouraging feedback on the topics you have taught, at no cost to them or to your school.</li>
    <li><strong>Insight for your teaching.</strong> See, without names, which topics your students find hardest, which helps your own revision lessons.</li>
    <li><strong>Free materials.</strong> Our free library of printable handouts is open for your classes.</li>
    <li><strong>Recognition.</strong> Your name, school and signature appear on every lesson and set of notes you check, and on lessons you teach as a guest.</li>
    <li><strong>A verifiable certificate of contribution</strong> listing what you have given, for your professional record and continuing professional development.</li>
    <li><strong>A community</strong> of teachers and volunteers who care about understanding, not memorising.</li>
</ul>
<p class="letter__box">Your time is your own: there are no meetings, no targets and no payment or favour of any kind, either way. You can stop at any time.</p>
